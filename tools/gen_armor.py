def h(c): c=c.lstrip('#'); return tuple(int(c[i:i+2],16) for i in (0,2,4))+(255,)
def icon(name,rects,pal,corrupt=False,visor=None):
    im=Image.new('RGBA',(16,16),(0,0,0,0)); px=im.load(); mask=set()
    for x0,y0,x1,y1 in rects:
        for y in range(y0,y1):
            for x in range(x0,x1): mask.add((x,y))
    for (x,y) in mask:
        up=(x,y-1) not in mask; lf=(x-1,y) not in mask; dn=(x,y+1) not in mask; rt=(x+1,y) not in mask
        right = corrupt and x>=8
        base=pal['dark_r'] if right else pal['mid']
        if up or lf: c=pal['dark_r2'] if right else pal['light']
        elif dn or rt: c=pal['edge']
        else:
            c=base
            if ((x*7+y*3)%5==0): c=pal['dark_r2'] if right else pal['mid2']
        if corrupt and right and (x*5+y*11)%7 in (0,3) and not (dn or rt or up or lf): c=h('D91E18')
        if corrupt and right and (x*3+y*5)%11==0: c=h('FF3B30')
        px[x,y]=c
    if visor:
        for (x,y) in visor:
            if (x,y) in mask: px[x,y]=pal['visor']
    im.save(f'out_icons/{name}.png')

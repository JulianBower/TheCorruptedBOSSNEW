    J.insert(-1,f'    /** Plain plate area used for the solid under-layer that covers the whole player part. */\n    static final float[] UV_{k} = {{ {fmt(x0/TEX)}, {fmt(y0/TEX)}, {fmt(x1/TEX)}, {fmt(y1/TEX)} }};')

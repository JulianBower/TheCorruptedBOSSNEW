    area=abs(q['uv'][2]-q['uv'][0])*abs(q['uv'][3]-q['uv'][1])
    key={'HEAD':'HEAD','TORSO':'BODY','R_ARM':'ARM','L_ARM':'ARM','R_LEG':'LEG','L_LEG':'LEG'}[b]
